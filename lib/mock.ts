const EXTRA: Seed[] = ['F', 'G', 'H', 'I', 'J'].map((c, i) => [
  `[가게명 ${c}]`, ['분식', '카레', '샐러드', '중식', '디저트'][i], '11:00~21:00', ['20대 여성', '30대 남성', '20대 여성', '40대 남성', '20대 여성'][i], '', 5 + i * 2, [],
]);

function split(hours: string): [string, string] {
  if (hours === '24시간') return ['00:00', '24:00'];
  const [a, b] = hours.split('~');
  return [a, b];
}

export function mockItems(mode: Mode = 'meal', limit = 10): EatplItem[] {
  return [...SEEDS[mode], ...EXTRA].slice(0, limit).map(([merNm, merTpbuzNm, hours, mainCust, reason, walk, tags], i) => {
    const [srtTime, endTime] = split(hours);
    return {
      merUrl: '', // 실제 응답에서는 잇플 상세 링크. 데모는 비워둠
      merNm, merTpbuzNm, srtTime, endTime, mainCust,
      _key: `${mode}-${i}`, _walkMin: walk, _tags: tags, _reason: reason,
    };
  });
}

// 상황 4가지 전부 (탭을 바로 바꿀 수 있게 한 번에 내려줌)
export function mockViewsByMode(limit = 10): Record<Mode, StoreView[]> {
  return Object.fromEntries(MODE_ORDER.map((m) => [m, toViews(mockItems(m, limit))])) as Record<Mode, StoreView[]>;
}
