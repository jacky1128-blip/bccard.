const norm = (s: string) => s.replace(/\s+/g, '').toUpperCase();
const NEEDLES = BRANDS.map(norm);

export function isFranchise(it: Pick<EatplItem, 'merNm'>) {
  const n = norm(it.merNm ?? '');
  return NEEDLES.some((b) => n.includes(b));
}

// 프랜차이즈를 빼되, 빼고 나서 너무 적으면(작은 동네) 프랜차이즈를 뒤에 붙여 목록이 비지 않게
// 순서는 그대로라 남은 가게끼리는 매출 순
export function dropFranchises<T extends Pick<EatplItem, 'merNm'>>(items: T[], min = 15): T[] {
  const indie = items.filter((it) => !isFranchise(it));
  return indie.length >= min ? indie : [...indie, ...items.filter(isFranchise)];
}
